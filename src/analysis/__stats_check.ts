c('2 solve -> gạch ngang', formatTime(averageOf([1000,2000])) === '—');
c('DNF thật -> DNF', formatTime(Infinity) === 'DNF');
c('ao5 bỏ nhanh nhất & chậm nhất', averageOf([1000,2000,3000,4000,5000]) === 3000, String(averageOf([1000,2000,3000,4000,5000])));
c('1 DNF vẫn tính được', averageOf([1000,2000,3000,4000,Infinity]) === 3000);
c('2 DNF -> DNF', averageOf([1000,2000,3000,Infinity,Infinity]) === Infinity);
c('bestAverage mảng ngắn -> DNF', bestAverage([1000,2000], 5) === Infinity);
