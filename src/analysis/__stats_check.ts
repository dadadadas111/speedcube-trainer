import { formatTime, averageOf, bestAverage } from './stats';
const c=(n:string,v:boolean,x='')=>console.log((v?'ok   ':'FAIL ')+n+(x?' <'+x+'>':''));
c('empty array -> dash', formatTime(averageOf([])) === '—', formatTime(averageOf([])));
c('2 solves -> dash', formatTime(averageOf([1000,2000])) === '—');
c('a real DNF -> DNF', formatTime(Infinity) === 'DNF');
c('ao5 drops the fastest and slowest', averageOf([1000,2000,3000,4000,5000]) === 3000, String(averageOf([1000,2000,3000,4000,5000])));
c('one DNF still averages', averageOf([1000,2000,3000,4000,Infinity]) === 3000);
c('two DNFs -> DNF', averageOf([1000,2000,3000,Infinity,Infinity]) === Infinity);
c('bestAverage on a short list -> DNF', bestAverage([1000,2000], 5) === Infinity);
c('formats minutes', formatTime(75230) === '1:15.23', formatTime(75230));
c('formats seconds', formatTime(12470) === '12.47', formatTime(12470));
