/**
 * Real solves by real Roux solvers, to be lived through rather than watched.
 *
 * Reconstructions from cubesolv.es, a community site that has not been updated
 * since the end of 2022 — which makes it a fixed set rather than a dependency.
 * Every one of these was CHECKED by the app's own cube: scramble plus solution
 * leaves a solved cube. Four of the forty-nine fetched did not, and are not
 * here. That check is the whole reason to hold a copy rather than link out:
 * hand-typed reconstructions are wrong often enough that following one blindly
 * wastes an evening, and no one can spot it by eye.
 *
 * Roux only, and decided by what the solver actually did rather than by who
 * they are: a solve counts if its own step names include CMLL and do not
 * include a cross. Filtering by name let six of Jules Desjardin's CFOP solves
 * in, which a Roux trainer has no business teaching.
 *
 * Each carries its solver, where it was done, and the id it came from, so the
 * original is always one link away: http://www.cubesolv.es/solve/<id>
 */

